@dataclass
class Pack:
    meta: PackMeta
    dir: Path
    chapters: list[PackChapter]
    sets: list[PackSet]
    items: list[PackItem]
    cards: list[PackCard]
    figures: list[PackFigure]
    bodies: dict[str, Any] | None  # parsed section_bodies.json, or None when missing


@dataclass
class Outline:
    nodes: list[OutlineNode]
    blueprint: list[BlueprintRow]
    crosswalk: dict[str, list[str]]
    source_id: str
    question_map: dict[str, list[str]]
    by_id: dict[str, OutlineNode] = field(default_factory=dict)

    def __post_init__(self) -> None:
        self.by_id = {n.id: n for n in self.nodes}

    @property
    def leaves(self) -> set[str]:
        return {n.id for n in self.nodes if n.leaf}

    def axis(self, kind: str, slug: str) -> str:
        prefix = {"discipline": "disc", "clinical_science": "cs", "task": "task"}[kind]
        return f"{OUTLINE_PREFIX}.{prefix}.{slug}"

    def with_ancestors(self, ids: list[str]) -> list[str]:
        """The ids plus every outline ancestor (category, system), deduplicated, in a stable order."""
        out: list[str] = []
        for i in ids:
            chain = [i]
            node = self.by_id.get(i)
            while node is not None and node.parent_id and node.parent_id != OUTLINE_PREFIX:
                chain.append(node.parent_id)
                node = self.by_id.get(node.parent_id)
            for c in chain:
                if c not in out:
                    out.append(c)
        return out


def _json(path: Path) -> Any:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def _err(what: str, exc: ValidationError) -> str:
    first = exc.errors()[0]
    return f"{what}: {'.'.join(map(str, first['loc']))}: {first['msg']}"


def load_outline(data_dir: Path, problems: list[str]) -> Outline | None:
    path = data_dir / TAXONOMY_FILE
    if not path.is_file():
        problems.append(f"{TAXONOMY_FILE}: missing; run `python tools/usmle2026.py`")
        return None
    try:
        doc = OutlineFile.model_validate(_json(path))
    except ValidationError as exc:
        problems.append(_err(str(TAXONOMY_FILE), exc))
        return None
    qmap_raw = _json(data_dir / TAXONOMY_QMAP_FILE) if (data_dir / TAXONOMY_QMAP_FILE).is_file() else {}
    qmap = {str(k): [str(x) for x in v] for k, v in qmap_raw.items()} if isinstance(qmap_raw, dict) else {}
    outline = Outline(doc.nodes, doc.blueprint, doc.crosswalk, doc.source_id, qmap)
    ids = set(outline.by_id)
    for n in doc.nodes:
        if n.parent_id is not None and n.parent_id not in ids:
            problems.append(f"{TAXONOMY_FILE}: node {n.id} has unknown parent {n.parent_id}")
    for r in doc.blueprint:
        if r.node_id not in ids:
            problems.append(f"{TAXONOMY_FILE}: blueprint row for unknown node {r.node_id}")
    for qid, tids in qmap.items():
        bad = [t for t in tids if t not in ids]
        if bad:
            problems.append(f"{TAXONOMY_QMAP_FILE}: question {qid}: unknown ids {bad}")
    return outline


def _load_list[T: BaseModel](model: type[T], path: Path, what: str, problems: list[str]) -> list[T]:
    if not path.is_file():
        return []
    raw = _json(path)
    if not isinstance(raw, list):
        problems.append(f"{what}: expected a list")
        return []
    out: list[T] = []
    for i, row in enumerate(raw):
        try:
            out.append(model.model_validate(row))
        except ValidationError as exc:
            ident = row.get("id", i) if isinstance(row, Mapping) else i
            problems.append(_err(f"{what}[{ident}]", exc))
    return out


def load_packs(data_dir: Path, problems: list[str]) -> list[Pack]:
    root = data_dir / CONTENT_DIR
    packs: list[Pack] = []
    if not root.is_dir():
        return packs
    for d in sorted(p for p in root.iterdir() if p.is_dir()):
        meta_path = d / "pack.json"
        if not meta_path.is_file():
            problems.append(f"content/{d.name}: no pack.json")
            continue
        try:
            meta = PackMeta.model_validate(_json(meta_path))
        except ValidationError as exc:
            problems.append(_err(f"content/{d.name}/pack.json", exc))
            continue
        if meta.id != d.name:
            problems.append(f"content/{d.name}/pack.json: id {meta.id!r} must equal the directory name")
        where = f"content/{d.name}"
        chapters = _load_list(PackChapter, d / "chapters.json", f"{where}/chapters", problems)
        figures = _load_list(PackFigure, d / "figures.json", f"{where}/figures", problems)
        cards = _load_list(PackCard, d / "cards.json", f"{where}/cards", problems)
        sets: list[PackSet] = []
        items: list[PackItem] = []
        qpath = d / "questions.json"
        if qpath.is_file():
            raw = _json(qpath)
            if not isinstance(raw, Mapping):
                problems.append(f'{where}/questions.json: expected {{"sets": [...], "items": [...]}}')
            else:
                extra = set(raw) - {"sets", "items"}
                if extra:
                    problems.append(f"{where}/questions.json: unknown keys {sorted(extra)}")
                for i, row in enumerate(raw.get("sets") or []):
                    try:
                        sets.append(PackSet.model_validate(row))
                    except ValidationError as exc:
                        problems.append(
                            _err(f"{where}/sets[{row.get('id', i) if isinstance(row, Mapping) else i}]", exc)
                        )
                for i, row in enumerate(raw.get("items") or []):
                    try:
                        items.append(PackItem.model_validate(row))
                    except ValidationError as exc:
                        problems.append(
                            _err(f"{where}/items[{row.get('id', i) if isinstance(row, Mapping) else i}]", exc)
                        )
        bodies = _json(d / PACK_BODIES) if (d / PACK_BODIES).is_file() else None
        pack = Pack(meta, d, chapters, sets, items, cards, figures, bodies)
        problems += pack_problems(pack)
        packs.append(pack)
    return packs


def pack_problems(p: Pack) -> list[str]:
    """Checks inside one pack: id prefixes, set shape, figure files. Cross-pack checks run in data.load_bundle."""
    out: list[str] = []
    where = f"content/{p.meta.id}"
    prefix = p.meta.id_prefix + "-"
    ids = (
        [("chapter", c.id) for c in p.chapters]
        + [("section", s.id) for c in p.chapters for s in c.sections]
        + [("figure", f.id) for f in p.figures]
        + [("set", s.id) for s in p.sets]
        + [("item", q.id) for q in p.items]
        + [("card", c.id) for c in p.cards]
    )
    for kind, i in ids:
        if not i.startswith(prefix):
            out.append(f"{where}: {kind} id {i} must start with the pack prefix {prefix!r}")
    sets = {s.id: s for s in p.sets}
    members: dict[str, list[int]] = {}
    for q in p.items:
        if q.set_id is None:
            continue
        s = sets.get(q.set_id)
        if s is None:
            out.append(f"{where}: item {q.id}: unknown set {q.set_id}")
            continue
        if s.kind != q.format:
            out.append(f"{where}: item {q.id}: format {q.format} differs from its set's kind {s.kind}")
        if s.exam != q.exam:
            out.append(f"{where}: item {q.id}: exam differs from its set's")
        assert q.set_order is not None
        members.setdefault(s.id, []).append(q.set_order)
    for sid, s in sets.items():
        orders = sorted(members.get(sid, []))
        lo = 2
        hi = 3 if s.kind == "sequential" else 9
        if orders != list(range(1, len(orders) + 1)) or not lo <= len(orders) <= hi:
            out.append(f"{where}: set {sid} ({s.kind}) needs {lo}-{hi} items numbered 1..n, has orders {orders}")
    for f in p.figures:
        if not (p.dir / f.file).is_file():
            out.append(f"{where}: figure {f.id}: missing file {f.file}")
    return out


def why_not_html(item: PackItem) -> str:
    """The legacy single-string form, so the existing explanation view shows every option's reason."""
    by_label = {o.label: o for o in item.options}
    parts = [
        f"<p><strong>{lab}.</strong> {item.why_not[lab]}</p>"
        for lab in LABELS
        if lab in item.why_not and lab in by_label
    ]
    return "".join(parts)


def answer_html(item: PackItem) -> str:
    opt = next(o for o in item.options if o.label == item.answer)
    return f"Answer: {item.answer}. {opt.html}"


def difficulty_bucket(level: int) -> Literal["easy", "medium", "hard"]:
    return "easy" if level <= 2 else "medium" if level == 3 else "hard"


def card_uuid(card_id: str) -> str:
    return str(uuid.uuid5(CARD_NAMESPACE, card_id))


def plain(text: str) -> str:
    return html.unescape(text)
