"""Content packs (`data/content/<pack>/`) and the USMLE-2026 taxonomy (`data/taxonomy/`): load, check, normalise.

One pack per author task, so parallel authors never edit the same file (docs/CONTENT_AUTHORING.md):

    data/content/<pack>/pack.json            id, title, owner, idPrefix, systems, retire[], retag{}
    data/content/<pack>/chapters.json        chapters -> sections (html with [[figure:id]], areas, furtherReading)
    data/content/<pack>/questions.json       {"sets": [...], "items": [...]}
    data/content/<pack>/cards.json           flashcards
    data/content/<pack>/figures.json         figures; files in data/content/<pack>/figures/
    data/content/<pack>/section_bodies.json  generated by `pnpm --filter @naadi/shared seed:convert`

Every pack row is normalised into the seed bundle's existing models (ChapterIn, FigureIn, QuestionIn) plus the
new SetIn / CardIn lists, so the importer upserts packs and the legacy files the same way (by id, idempotent).
Pure: no database, no network.
"""

from __future__ import annotations

import html
import json
import uuid
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

CONTENT_DIR = "content"
TAXONOMY_FILE = Path("taxonomy") / "usmle2026.json"
TAXONOMY_QMAP_FILE = Path("taxonomy") / "usmle2026_question_map.json"
PACK_BODIES = "section_bodies.json"
OUTLINE_VERSION = "USMLE-2026"
LEGACY_VERSION = "naadi-legacy"
OUTLINE_PREFIX = "usmle2026"
# Seed flashcards get a stable uuid from their pack id, so a re-import upserts instead of duplicating.
CARD_NAMESPACE = uuid.UUID("6e616164-692d-4361-7264-732d32303236")

Exam = Literal["step1", "step2ck"]
ID = r"^[a-z0-9][a-z0-9_.-]{0,127}$"
PACK_ID = r"^[a-z0-9][a-z0-9-]{0,63}$"
LABELS = "ABCDEFGHIJ"


class _In(BaseModel):
    model_config = ConfigDict(extra="forbid", populate_by_name=True)


# ── USMLE-2026 taxonomy file ──


class OutlineNode(_In):
    id: str = Field(pattern=r"^usmle2026(\.[a-z0-9_]+)*$")
    kind: Literal[
        "outline", "outline_system", "outline_category", "outline_area", "discipline", "clinical_science", "task"
    ]
    parent_id: str | None
    code: str | None
    level: int | None
    label: str = Field(min_length=1, max_length=200)
    exam: list[Exam] = Field(min_length=1)
    sort: int
    example_lines: int | None = Field(default=None, alias="exampleLines")
    leaf: bool = False


class BlueprintRow(_In):
    node_id: str = Field(alias="nodeId")
    exam: Exam
    row: str
    row_label: str = Field(alias="rowLabel")
    weight_min: float = Field(alias="weightMin")
    weight_max: float = Field(alias="weightMax")
    share: int = Field(ge=0)
    min_items: int = Field(alias="minItems", ge=0)
    target_items: int = Field(alias="targetItems", ge=0)
    tested: bool


class OutlineFile(_In):
    outline_version: Literal["USMLE-2026"] = Field(alias="outlineVersion")
    source_id: str = Field(alias="sourceId")
    generator: str
    note: str
    nodes: list[OutlineNode]
    blueprint: list[BlueprintRow]
    crosswalk: dict[str, list[str]]


# ── pack files ──


