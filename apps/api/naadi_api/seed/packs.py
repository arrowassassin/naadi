class PackFigure(_In):
    id: str = Field(pattern=ID)
    chapter_id: str = Field(alias="chapterId")
    caption: str = Field(min_length=1)
    file: str = Field(pattern=r"^figures/[a-z0-9_.-]+\.svg$")
    source: str = "naadi-original-v1"
    attribution: str | None = None


class PackOption(_In):
    label: str = Field(pattern=r"^[A-J]$")
    html: str = Field(min_length=1)


class PackReview(BaseModel):
    model_config = ConfigDict(extra="allow", populate_by_name=True)
    status: Literal["draft", "self_reviewed", "in_review", "approved", "changes_requested"] = "draft"
    human_expert_reviewed: bool = Field(alias="humanExpertReviewed", default=False)
    author: str = Field(min_length=1)


class PackSet(_In):
    id: str = Field(pattern=ID)
    exam: Exam
    kind: Literal["sequential", "abstract"]
    title: str | None = None
    intro_html: str | None = Field(alias="introHtml", default=None)
    source: str = "naadi-original-v1"

    @model_validator(mode="after")
    def _abstract_has_intro(self) -> PackSet:
        if self.kind == "abstract" and not (self.intro_html or "").strip():
            raise ValueError("an abstract set needs introHtml (the study summary)")
        return self


class PackItem(_In):
    id: str = Field(pattern=ID)
    exam: Exam
    format: Literal["single", "chart", "sequential", "abstract"] = "single"
    set_id: str | None = Field(alias="setId", default=None)
    set_order: int | None = Field(alias="setOrder", default=None, ge=1, le=9)
    chapter_id: str | None = Field(alias="chapterId", default=None)
    stem_html: str = Field(alias="stemHtml", min_length=1)
    options: list[PackOption] = Field(min_length=5, max_length=10)
    answer: str = Field(pattern=r"^[A-J]$")
    explanation_html: str = Field(alias="explanationHtml", min_length=1)
    why_not: dict[str, str] = Field(alias="whyNot")
    objective: str = Field(min_length=1)
    areas: list[str] = Field(min_length=1, max_length=3)
    disciplines: list[str] = Field(default_factory=list)
    clinical_sciences: list[str] = Field(alias="clinicalSciences", default_factory=list)
    tasks: list[str] = Field(default_factory=list)
    difficulty: int = Field(ge=1, le=5)
    source: str = "naadi-original-v1"
    references: list[str] = Field(default_factory=list, description="link-only sources the facts follow")
    figure_ids: list[str] = Field(alias="figureIds", default_factory=list)
    tags: list[str] = Field(default_factory=list)
    status: Literal["draft", "in_review", "published"] = "published"
    review: PackReview

    @model_validator(mode="after")
    def _shape(self) -> PackItem:
        labels = [o.label for o in self.options]
        if labels != list(LABELS[: len(labels)]):
            raise ValueError("options must be labelled A, B, C... in order")
        if self.answer not in labels:
            raise ValueError(f"answer {self.answer} is not an option")
        wrong = set(labels) - {self.answer}
        if set(self.why_not) != wrong:
            raise ValueError(f"whyNot needs exactly the wrong options {sorted(wrong)}, got {sorted(self.why_not)}")
        if any(not v.strip() for v in self.why_not.values()):
            raise ValueError("whyNot text is empty")
        in_set = self.format in ("sequential", "abstract")
        if in_set != (self.set_id is not None) or (self.set_id is None) != (self.set_order is None):
            raise ValueError("sequential/abstract items need setId and setOrder; other formats have neither")
        return self


