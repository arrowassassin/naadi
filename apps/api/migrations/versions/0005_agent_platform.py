"""Agent platform: usage purpose, search ledger, agent health log, Aegra tables closed to clients.

Revision ID: 0005
Revises: 0004
Create Date: 2026-11-16

- `llm_usage.purpose` ('chat' | 'job'): the daily cap is split per provider, `reserve_for_chat` for the tutor
  and the rest for jobs (naadi_api/llm_budget.py counts rows per provider and purpose since 00:00 UTC).
- `search_usage`: our own Tavily ledger (one row per paid search: user, credits). The per-user daily cap and
  the monthly credit stop are counted from it; Tavily's usage endpoint is never polled per request.
- `agent_health`: results of the runtime self-test (`ping` graph): interactive, background and the hourly
  system cron. `/api/health` reads the latest cron row.
- Aegra and LangGraph keep their own tables in `public` (assistant, thread, runs, crons, checkpoints, store,
  ...). Default privileges (0001) already grant anon/authenticated nothing on them; this migration adds
  `public.naadi_secure_aegra_tables()`, which enables row-level security on each of them that exists and
  revokes any client privilege, and calls it. Aegra creates its tables at container start, so the startup
  migration (naadi_api/agent/migrate_all.py) runs Aegra's migrations first and calls the function again
  after Naadi's, then refuses to start if any table in `public` still lacks RLS.

All three new tables are server-side only: RLS enabled and forced, no client privileges, service role only.
"""

from __future__ import annotations

from collections.abc import Sequence

from alembic import op

revision: str = "0005"
down_revision: str | None = "0004"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

AEGRA_TABLES = (
    "alembic_version",
    "assistant",
    "assistant_versions",
    "thread",
    "runs",
    "crons",
    "thread_ttl",
    "checkpoints",
    "checkpoint_blobs",
    "checkpoint_writes",
    "checkpoint_migrations",
    "store",
    "store_migrations",
)
_ARRAY = "array[" + ",".join(f"'{t}'" for t in AEGRA_TABLES) + "]::text[]"

UPGRADE = f"""
alter table public.llm_usage
  add column purpose text not null default 'chat' check (purpose in ('chat','job'));
create index llm_usage_provider_purpose_created_idx on public.llm_usage (provider, purpose, created_at);

create table public.search_usage (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  source text not null check (source in ('tavily')),
  credits smallint not null check (credits > 0),
  created_at timestamptz not null default now()
);
create index search_usage_source_created_idx on public.search_usage (source, created_at);
create index search_usage_user_created_idx on public.search_usage (user_id, created_at) where user_id is not null;

create table public.agent_health (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('ping')),
  trigger text not null check (trigger in ('interactive','background','cron')),
  ok boolean not null,
  run_id text,
  provider text check (provider is null or provider in ('nvidia','openrouter')),
  model text,
  latency_ms int check (latency_ms is null or latency_ms >= 0),
  detail jsonb not null default '{{}}' check (jsonb_typeof(detail) = 'object'),
  created_at timestamptz not null default now()
);
create index agent_health_kind_trigger_created_idx on public.agent_health (kind, trigger, created_at desc);

alter table public.search_usage enable row level security;
alter table public.search_usage force row level security;
alter table public.agent_health enable row level security;
alter table public.agent_health force row level security;
revoke all on table public.search_usage, public.agent_health from anon, authenticated;
grant all on table public.search_usage, public.agent_health to service_role;
revoke all on sequence public.search_usage_id_seq, public.agent_health_id_seq from anon, authenticated;

create function public.naadi_secure_aegra_tables() returns int
language plpgsql set search_path = '' as $$
declare
  t text;
  n int := 0;
begin
  foreach t in array {_ARRAY} loop
    if to_regclass('public.' || quote_ident(t)) is not null then
      execute format('alter table public.%I enable row level security', t);
      execute format('revoke all on table public.%I from anon, authenticated', t);
      n := n + 1;
    end if;
  end loop;
  return n;
end
$$;
revoke all on function public.naadi_secure_aegra_tables() from public, anon, authenticated;
select public.naadi_secure_aegra_tables();
"""

DOWNGRADE_TABLES = """
drop function if exists public.naadi_secure_aegra_tables();
drop table if exists public.agent_health;
drop table if exists public.search_usage;
"""
DOWNGRADE_USAGE = """
drop index if exists public.llm_usage_provider_purpose_created_idx;
alter table public.llm_usage drop column if exists purpose;
"""


def upgrade() -> None:
    op.execute(UPGRADE)


def downgrade() -> None:
    # Aegra's tables keep RLS on downgrade: turning it off would open them, and nothing here created them.
    op.execute(DOWNGRADE_TABLES)
    op.execute(DOWNGRADE_USAGE)
