import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import {
  type CardMemory,
  CardState,
  configFromServer,
  DEFAULT_FSRS_CONFIG,
  fnv1a32,
  localDate,
  memoryFromSchedule,
  mulberry32First,
  NEW_CARD,
  pyRound,
  type Rating,
  Scheduler,
  type ServerSchedulerConfig,
} from "./fsrs";

interface Expect {
  state: number;
  step: number | null;
  stability: number;
  difficulty: number;
  due: string;
  due_ms: number;
  due_local_date: string;
  elapsed_days: number;
  scheduled_days: number;
  reps: number;
  lapses: number;
}
interface Golden {
  tolerance: { stability_rel: number; difficulty_abs: number };
  configs: Record<string, ServerSchedulerConfig>;
  cases: {
    id: string;
    config: string;
    card_id: string;
    zone: string;
    reviews: { at: string; at_ms: number; rating: Rating; expect: Expect }[];
  }[];
}

// Generated by the API's scheduler (official Python `fsrs`): apps/api/tests/cards/golden.py
const golden: Golden = JSON.parse(
  readFileSync(resolve(__dirname, "../../../../packages/shared/fixtures/fsrs-golden.json"), "utf8"),
);

describe("FSRS parity with the API scheduler (shared golden vectors)", () => {
  it("covers DST, half-hour and 45-minute zones and every config", () => {
    const zones = new Set(golden.cases.map((c) => c.zone));
    for (const z of ["America/New_York", "Europe/London", "Australia/Lord_Howe", "Pacific/Chatham", "Asia/Kolkata"]) {
      expect(zones.has(z)).toBe(true);
    }
    expect(Object.keys(golden.configs).sort()).toEqual(["custom", "defaults", "fuzz"]);
    expect(golden.cases.length).toBeGreaterThanOrEqual(300);
  });

  it("gives the same state, step, due time, intervals and local due day for every review", () => {
    const { stability_rel, difficulty_abs } = golden.tolerance;
    let n = 0;
    for (const c of golden.cases) {
      const sch = new Scheduler(configFromServer(golden.configs[c.config] as ServerSchedulerConfig));
      let card: CardMemory = NEW_CARD;
      for (const r of c.reviews) {
        const at = new Date(r.at);
        expect(at.getTime(), c.id).toBe(r.at_ms);
        const out = sch.review(c.card_id, card, r.rating, at);
        card = out.card;
        const e = r.expect;
        const where = `${c.id} @ ${r.at}`;
        expect(
          [card.state, card.step, card.due?.getTime(), out.scheduledDays, out.elapsedDays, card.reps, card.lapses],
          where,
        ).toEqual([e.state, e.step, e.due_ms, e.scheduled_days, e.elapsed_days, e.reps, e.lapses]);
        expect(Math.abs((card.stability as number) - e.stability) / e.stability, where).toBeLessThanOrEqual(
          stability_rel,
        );
        expect(Math.abs((card.difficulty as number) - e.difficulty), where).toBeLessThanOrEqual(difficulty_abs);
        expect(localDate(card.due as Date, c.zone), where).toBe(e.due_local_date);
        n += 1;
      }
    }
    expect(n).toBeGreaterThan(3000);
  });

  it("uses the shipped defaults (ts-fsrs 6.0.0 = fsrs 6.3.3)", () => {
    expect(configFromServer(golden.configs.defaults as ServerSchedulerConfig)).toEqual({
      ...DEFAULT_FSRS_CONFIG,
      weights: [...DEFAULT_FSRS_CONFIG.weights],
      learningStepsSeconds: [...DEFAULT_FSRS_CONFIG.learningStepsSeconds],
      relearningStepsSeconds: [...DEFAULT_FSRS_CONFIG.relearningStepsSeconds],
    });
  });
});

describe("seeded fuzz RNG (same values the API's Python port produces)", () => {
  it.each([
    ["", 2166136261, 0.6112444521859288],
    ["naadi", 3247223012, 0.4315809740219265],
    ["ä€😀", 922931504, 0.2629598416388035],
  ])("%s", (seed, hash, first) => {
    expect(fnv1a32(seed)).toBe(hash);
    expect(mulberry32First(hash)).toBe(first);
  });
});

describe("preview", () => {
  it("gives one outcome per rating, each the same as reviewing with it", () => {
    const sch = new Scheduler();
    const at = new Date("2026-11-16T08:00:00Z");
    const p = sch.preview("c1", NEW_CARD, at);
    expect(p[1].intervalMs).toBe(60_000);
    expect(p[2].intervalMs).toBe(330_000); // Hard on the first step: halfway between 1 and 10 minutes
    expect(p[3].intervalMs).toBe(600_000);
    expect(p[4].card.state).toBe(CardState.Review);
    expect(p[3]).toEqual(sch.review("c1", NEW_CARD, 3, at));
  });

  it("reads the server's schedule shape", () => {
    expect(memoryFromSchedule({ state: 0, reps: 0, lapses: 0 })).toBe(NEW_CARD);
    const m = memoryFromSchedule({
      state: 2,
      step: null,
      stability: 3.1,
      difficulty: 5.5,
      due: "2026-11-20T08:00:00Z",
      last_review: "2026-11-16T08:00:00Z",
      reps: 4,
      lapses: 1,
    });
    expect(m.due?.toISOString()).toBe("2026-11-20T08:00:00.000Z");
    expect(m.lastReview?.toISOString()).toBe("2026-11-16T08:00:00.000Z");
  });
});

describe("whole-day intervals (as the Python package rounds them)", () => {
  it("rounds ties to even", () => {
    expect([0.5, 1.5, 2.5, 3.5, -2.5, 2.4999, 2.5001].map(pyRound)).toEqual([0, 2, 2, 4, -2, 2, 3]);
  });

  it("matches fsrs 6.3.3's _next_interval at the default retention, where the interval equals the stability", () => {
    const sch = new Scheduler();
    // values printed by the Python package: Scheduler()._next_interval(stability=s)
    expect([0.4, 1.5, 2.5, 3.5, 7.25].map((s) => sch["nextInterval"](s))).toEqual([1, 2, 2, 4, 7]);
  });
});
