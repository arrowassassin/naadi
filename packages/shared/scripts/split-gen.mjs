// Splits the generated SDK and zod schemas into one module per export (segment 22 performance budget).
//
// @hey-api/openapi-ts writes every SDK function to sdk.gen.ts and every schema to zod.gen.ts. Bundlers split chunks
// by module, so one module that any route touches lands whole in a chunk the first page loads (~110 KB gzip with
// zod). With one module per export, each route's chunk carries only the calls and schemas it uses.
//
// Runs after `openapi-ts` in `pnpm gen` (idempotent: it reads the generator's single-file output, writes
// src/gen/sdk/*.ts and src/gen/zod/*.ts, and turns sdk.gen.ts and zod.gen.ts into re-export barrels, so every
// existing import keeps working). Each schema module imports ../../zod-config first, so `z.config({ jitless: true })`
// runs before any schema is constructed whichever chunk evaluates first.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GEN = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "src", "gen");
const HEADER = "// This file is auto-generated by @hey-api/openapi-ts (split by scripts/split-gen.mjs)\n";
const BARREL_MARK = "// split-gen barrel";

/** Top-level declarations of a biome-formatted generated file: [{ name, text }] plus the import section. */
function declarations(source) {
  const lines = source.split("\n");
  const decls = [];
  let head = [];
  let current = null;
  let pendingComment = [];
  let inComment = false;
  let seenDecl = false;
  for (const line of lines) {
    if (!seenDecl && !line.startsWith("/**") && !line.startsWith("export ") && !inComment) {
      head.push(line);
      continue;
    }
    if (line.startsWith("/**")) {
      inComment = true;
      seenDecl = true;
      if (current) {
        decls.push(current);
        current = null;
      }
      pendingComment = [line];
      if (line.includes("*/")) inComment = false;
      continue;
    }
    if (inComment) {
      pendingComment.push(line);
      if (line.startsWith(" */")) inComment = false;
      continue;
    }
    const m = /^export (?:const|type) (\w+)/.exec(line);
    if (m) {
      seenDecl = true;
      if (current) decls.push(current);
      current = { name: m[1], lines: [...pendingComment, line] };
      pendingComment = [];
      continue;
    }
    if (current) current.lines.push(line);
    else if (line.trim()) throw new Error(`split-gen: unexpected top-level line: ${line}`);
  }
  if (current) decls.push(current);
  head = head.join("\n");
  return { head, decls: decls.map((d) => ({ name: d.name, text: `${d.lines.join("\n").trimEnd()}\n` })) };
}

const identifiers = (text) => new Set(text.match(/\b[A-Za-z_$][\w$]*\b/g));

function writeDir(dir, files) {
  fs.mkdirSync(dir, { recursive: true });
  const keep = new Set(Object.keys(files));
  for (const f of fs.readdirSync(dir)) if (!keep.has(f)) fs.rmSync(path.join(dir, f));
  for (const [f, text] of Object.entries(files)) fs.writeFileSync(path.join(dir, f), text);
}

const zodPath = path.join(GEN, "zod.gen.ts");
const sdkPath = path.join(GEN, "sdk.gen.ts");
const zodSrc = fs.readFileSync(zodPath, "utf8");
const sdkSrc = fs.readFileSync(sdkPath, "utf8");
if (zodSrc.includes(BARREL_MARK) || sdkSrc.includes(BARREL_MARK)) {
  throw new Error("split-gen: sdk.gen.ts / zod.gen.ts are already barrels; run openapi-ts first (pnpm gen)");
}

// zod schemas
const zod = declarations(zodSrc);
const zodNames = new Set(zod.decls.map((d) => d.name));
const zodFiles = {};
for (const d of zod.decls) {
  const ids = identifiers(d.text);
  const deps = [...zodNames].filter((n) => n !== d.name && ids.has(n)).sort();
  const imports = [
    'import "../../zod-config";',
    "",
    ...(/\bz\./.test(d.text) ? ['import * as z from "zod";'] : []),
    ...deps.map((n) => `import { ${n} } from "./${n}";`),
  ];
  zodFiles[`${d.name}.ts`] = `${HEADER}\n${imports.join("\n")}\n\n${d.text}`;
}
writeDir(path.join(GEN, "zod"), zodFiles);

// SDK functions
const sdk = declarations(sdkSrc);
const typeImport = /import type \{([^}]*)\} from "\.\/types\.gen";/.exec(sdk.head);
if (!typeImport) throw new Error("split-gen: sdk.gen.ts has no types.gen import");
const typeNames = new Set(
  typeImport[1]
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean),
);
const clientImport = /import type \{([^}]*)\} from "\.\/client";/.exec(sdk.head);
if (!clientImport) throw new Error("split-gen: sdk.gen.ts has no ./client type import");
const clientTypes = clientImport[1]
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean);
const sdkFiles = {};
const typeDecls = sdk.decls.filter((d) => d.text.includes(`export type ${d.name}`));
const fnDecls = sdk.decls.filter((d) => !typeDecls.includes(d));
const typeFile = (d) => `_${d.name}.ts`;
for (const d of [...typeDecls, ...fnDecls]) {
  const ids = identifiers(d.text);
  const out = [];
  if (/\bz\./.test(d.text)) out.push('import "../../zod-config";', "", 'import * as z from "zod";');
  const ct = clientTypes.filter((t) => ids.has(t.split(" as ").pop().trim()));
  if (ct.length) out.push(`import type { ${ct.join(", ")} } from "../client";`);
  if (/\?\? client\)/.test(d.text)) out.push('import { client } from "../client.gen";');
  const tn = [...typeNames].filter((t) => ids.has(t)).sort();
  if (tn.length) out.push(`import type { ${tn.join(", ")} } from "../types.gen";`);
  for (const t of typeDecls) {
    if (t !== d && ids.has(t.name)) out.push(`import type { ${t.name} } from "./_${t.name}";`);
  }
  for (const n of [...zodNames].filter((n) => ids.has(n)).sort()) out.push(`import { ${n} } from "../zod/${n}";`);
  const file = typeDecls.includes(d) ? typeFile(d) : `${d.name}.ts`;
  sdkFiles[file] = `${HEADER}\n${out.join("\n")}\n\n${d.text}`;
}
writeDir(path.join(GEN, "sdk"), sdkFiles);

// Barrels in place of the single files, so `./gen/sdk.gen` and `./gen/zod.gen` keep their exports.
const barrel = (lines) => `${HEADER}${BARREL_MARK}: do not edit; run \`pnpm gen\`\n\n${lines.join("\n")}\n`;
fs.writeFileSync(zodPath, barrel(zod.decls.map((d) => `export { ${d.name} } from "./zod/${d.name}";`)));
fs.writeFileSync(
  sdkPath,
  barrel([
    ...typeDecls.map((d) => `export type { ${d.name} } from "./sdk/_${d.name}";`),
    ...fnDecls.map((d) => `export { ${d.name} } from "./sdk/${d.name}";`),
  ]),
);
process.stdout.write(`split-gen: ${zod.decls.length} schemas, ${fnDecls.length} SDK functions\n`);
