#!/usr/bin/env python3
"""Build the renal-endo-nutrition pack files from the per-area authoring fragments in src/.

    cd apps/api
    P=../../data/content/renal-endo-nutrition
    uv run python $P/build.py --check $P/src/11.01.01.json
    uv run python ../../data/content/renal-endo-nutrition/build.py          # check every fragment, write the pack files

One fragment per USMLE-2026 leaf area (src/<code>.json), so several writers can work at once without touching the
same file. A fragment holds that area's sections, figures, sets, items and cards:

    {"area": "usmle2026.11.01.01",
     "sections": [{"id", "exam", "heading", "html", "figureIds", "areas", "furtherReading"}],
     "figures":  [{"id", "caption", "file", "source"?, "attribution"?}],
     "sets":     [PackSet rows], "items": [PackItem rows, chapterId optional], "cards": [PackCard rows]}

The build groups sections into one chapter per (chapter group, Step), fills in chapterId on items and figures, and
writes chapters.json, questions.json, cards.json and figures.json (sorted, deterministic). section_bodies.json is
still generated by `pnpm --filter @naadi/shared seed:convert` afterwards.

Pure and local: reads and writes files in this directory only.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from naadi_api.seed.packs import PackCard, PackFigure, PackItem, PackSection, PackSet

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PREFIX = "s23c-"

# chapter group -> (title, order for step1, order for step2ck)
GROUPS = {
    "11": ("Renal & urinary system", 311, 411),
    "15": ("Endocrine system", 315, 415),
    "16n": ("Nutrition", 316, 416),
    "16f": ("Fluids, electrolytes & acid-base", 317, 417),
}
STEP = {"step1": ("s1", "Step 1"), "step2ck": ("s2", "Step 2 CK")}
BANNED = re.compile(r"\b(all|none) of the above\b|\bexcept\b", re.I)


def group_of(area: str) -> str:
    code = area.removeprefix("usmle2026.")
    if code.startswith("16.04"):
        return "16n"
    if code.startswith("16.07"):
        return "16f"
    return code[:2]


def chapter_id(group: str, exam: str) -> str:
    return f"{PREFIX}ch{group}-{STEP[exam][0]}"


def taxonomy() -> tuple[set[str], dict[str, set[str]]]:
    doc = json.loads((ROOT / "data/taxonomy/usmle2026.json").read_text(encoding="utf-8"))
    leaves = {n["id"] for n in doc["nodes"] if n.get("leaf")}
    axes: dict[str, set[str]] = {"discipline": set(), "clinical_science": set(), "task": set()}
    for n in doc["nodes"]:
        if n["kind"] in axes:
            axes[n["kind"]].add(n["id"].rsplit(".", 1)[1])
    return leaves, axes


def sources() -> set[str]:
    text = (ROOT / "config/sources.yaml").read_text(encoding="utf-8")
    return set(re.findall(r"^\s*-\s*id:\s*([a-z0-9-]+)\s*$", text, re.M))


def check_fragment(path: Path, leaves: set[str], axes: dict[str, set[str]], srcs: set[str]) -> tuple[dict, list[str]]:
    probs: list[str] = []
    name = path.name
    try:
        frag = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return {}, [f"{name}: invalid JSON: {exc}"]
    area = frag.get("area")
    if area not in leaves:
        probs.append(f"{name}: area {area!r} is not a USMLE-2026 leaf")
    extra = set(frag) - {"area", "sections", "figures", "sets", "items", "cards", "notes"}
    if extra:
        probs.append(f"{name}: unknown keys {sorted(extra)}")

    def ids_ok(kind: str, rows: list[dict]) -> None:
        for r in rows:
            i = r.get("id", "?")
            if not str(i).startswith(PREFIX):
                probs.append(f"{name}: {kind} id {i} must start with {PREFIX}")

    secs = frag.get("sections", [])
    figs = frag.get("figures", [])
    sets = frag.get("sets", [])
    items = frag.get("items", [])
    cards = frag.get("cards", [])
    for kind, rows in (("section", secs), ("figure", figs), ("set", sets), ("item", items), ("card", cards)):
        ids_ok(kind, rows)
    for s in secs:
        row = {k: v for k, v in s.items() if k != "exam"}
        if s.get("exam") not in STEP:
            probs.append(f"{name}: section {s.get('id')} needs exam step1|step2ck")
        try:
            sec = PackSection.model_validate(row)
        except Exception as exc:  # noqa: BLE001 - report every row
            probs.append(f"{name}: section {s.get('id')}: {str(exc).splitlines()[0:3]}")
            continue
        placed = re.findall(r"\[\[figure:([a-z0-9_.-]+)\]\]", sec.html)
        if placed != sec.figure_ids:
            probs.append(f"{name}: section {sec.id}: figureIds {sec.figure_ids} != placeholders {placed}")
        if re.search(r"<a[\s>]", sec.html):
            probs.append(f"{name}: section {sec.id}: no links in the body")
        for a in sec.areas:
            if a not in leaves:
                probs.append(f"{name}: section {sec.id}: area {a} not a leaf")
        for fr in sec.further_reading:
            if fr.source_id not in srcs:
                probs.append(f"{name}: section {sec.id}: furtherReading source {fr.source_id} not in sources.yaml")
        if not sec.further_reading:
            probs.append(f"{name}: section {sec.id}: needs furtherReading")
    for f in figs:
        try:
            fig = PackFigure.model_validate({**f, "chapterId": "x"})
        except Exception as exc:  # noqa: BLE001
            probs.append(f"{name}: figure {f.get('id')}: {str(exc).splitlines()[0:3]}")
            continue
        if not (HERE / fig.file).is_file():
            probs.append(f"{name}: figure {fig.id}: file {fig.file} missing")
        if fig.source not in srcs:
            probs.append(f"{name}: figure {fig.id}: source {fig.source} unknown")
    for s in sets:
        try:
            PackSet.model_validate(s)
        except Exception as exc:  # noqa: BLE001
            probs.append(f"{name}: set {s.get('id')}: {str(exc).splitlines()[0:3]}")
    set_ids = {s.get("id") for s in sets}
    for q in items:
        try:
            item = PackItem.model_validate(q)
        except Exception as exc:  # noqa: BLE001
            probs.append(f"{name}: item {q.get('id')}: {str(exc).splitlines()[0:4]}")
            continue
        for a in item.areas:
            if a not in leaves:
                probs.append(f"{name}: item {item.id}: area {a} not a leaf")
        for kind, vals in (
            ("discipline", item.disciplines),
            ("clinical_science", item.clinical_sciences),
            ("task", item.tasks),
        ):
            bad = [v for v in vals if v not in axes[kind]]
            if bad:
                probs.append(f"{name}: item {item.id}: unknown {kind} {bad}")
        for r in item.references:
            if r not in srcs:
                probs.append(f"{name}: item {item.id}: reference {r} not in sources.yaml")
        if item.set_id and item.set_id not in set_ids:
            probs.append(f"{name}: item {item.id}: set {item.set_id} not in this fragment")
        texts = [item.stem_html] + [o.html for o in item.options]
        if any(BANNED.search(t) for t in texts):
            probs.append(f"{name}: item {item.id}: 'all/none of the above' or EXCEPT stem")
        if not item.tasks:
            probs.append(f"{name}: item {item.id}: needs a task tag")
        if item.exam == "step1" and not item.disciplines:
            probs.append(f"{name}: item {item.id}: step1 item needs a discipline")
        if item.exam == "step2ck" and not item.clinical_sciences:
            probs.append(f"{name}: item {item.id}: step2ck item needs a clinical science")
        if "Takeaway" not in item.explanation_html:
            probs.append(f"{name}: item {item.id}: explanation needs a Takeaway line")
        lens = [len(re.sub(r"<[^>]+>", "", o.html)) for o in item.options]
        right = lens[ord(item.answer) - 65]
        if right > 2.2 * (sum(lens) - right) / max(1, len(lens) - 1) and right > 60:
            probs.append(f"{name}: item {item.id}: the key is much longer than the distractors (length clue)")
    sec_ids = {s.get("id") for s in secs}
    item_ids = {q.get("id") for q in items}
    for c in cards:
        try:
            card = PackCard.model_validate(c)
        except Exception as exc:  # noqa: BLE001
            probs.append(f"{name}: card {c.get('id')}: {str(exc).splitlines()[0:3]}")
            continue
        if card.section_id and card.section_id not in sec_ids:
            probs.append(f"{name}: card {card.id}: section {card.section_id} not in this fragment")
        if card.question_id and card.question_id not in item_ids:
            probs.append(f"{name}: card {card.id}: question {card.question_id} not in this fragment")
        for a in card.areas:
            if a not in leaves:
                probs.append(f"{name}: card {card.id}: area {a} not a leaf")
    placed = {fid for s in secs for fid in s.get("figureIds", [])} | {
        fid for q in items for fid in q.get("figureIds", [])
    }
    for f in figs:
        if f.get("id") not in placed:
            probs.append(f"{name}: figure {f.get('id')} is not placed in a section or item")
    for fid in placed - {f.get("id") for f in figs}:
        probs.append(f"{name}: figure {fid} is used but not defined in this fragment")
    return frag, probs


def build(frags: list[dict]) -> tuple[list, dict, list, list]:
    chapters: dict[str, dict] = {}
    figures: list[dict] = []
    sets: list[dict] = []
    items: list[dict] = []
    cards: list[dict] = []
    for frag in frags:
        grp = group_of(frag["area"])
        fig_chapter: dict[str, str] = {}
        for s in frag.get("sections", []):
            cid = chapter_id(grp, s["exam"])
            title, o1, o2 = GROUPS[grp]
            ch = chapters.setdefault(
                cid,
                {
                    "id": cid,
                    "exam": s["exam"],
                    "order": o1 if s["exam"] == "step1" else o2,
                    "title": f"{STEP[s['exam']][1]} · {title}",
                    "meta": "Naadi original · USMLE-2026 outline",
                    "source": "naadi-original-v1",
                    "sections": [],
                },
            )
            ch["sections"].append({k: v for k, v in s.items() if k != "exam"})
            for fid in s.get("figureIds", []):
                fig_chapter.setdefault(fid, cid)
        for q in frag.get("items", []):
            q = dict(q)
            q.setdefault("chapterId", chapter_id(grp, q["exam"]))
            for fid in q.get("figureIds", []):
                fig_chapter.setdefault(fid, q["chapterId"])
            items.append(q)
        for f in frag.get("figures", []):
            figures.append(
                {"id": f["id"], "chapterId": fig_chapter[f["id"]], **{k: v for k, v in f.items() if k != "id"}}
            )
        sets += frag.get("sets", [])
        cards += frag.get("cards", [])
    # items may name a chapter that has no section yet (no section for that Step): drop the link then.
    for q in items:
        if q["chapterId"] not in chapters:
            del q["chapterId"]
    chs = sorted(chapters.values(), key=lambda c: (c["order"], c["id"]))
    return chs, {"sets": sets, "items": items}, cards, figures


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", nargs="*", type=Path, help="only check these fragments; write nothing")
    p.add_argument("--glob", default="*.json", help="which src/ fragments to build (default: all)")
    args = p.parse_args(argv)
    leaves, axes = taxonomy()
    srcs = sources()
    paths = args.check if args.check else sorted((HERE / "src").glob(args.glob))
    frags, probs = [], []
    for path in paths:
        frag, pr = check_fragment(path, leaves, axes, srcs)
        frags.append(frag)
        probs += pr
    seen: dict[str, str] = {}
    for path, frag in zip(paths, frags, strict=True):
        for kind in ("sections", "figures", "sets", "items", "cards"):
            for r in frag.get(kind, []):
                i = r.get("id")
                if i in seen:
                    probs.append(f"{path.name}: duplicate id {i} (also in {seen[i]})")
                seen[i] = path.name
    for line in probs:
        print(f"ERROR {line}", file=sys.stderr)
    n_items = sum(len(f.get("items", [])) for f in frags)
    n_secs = sum(len(f.get("sections", [])) for f in frags)
    n_cards = sum(len(f.get("cards", [])) for f in frags)
    print(f"{len(paths)} fragment(s): {n_secs} sections, {n_items} items, {n_cards} cards; {len(probs)} problem(s)")
    if probs:
        return 1
    if args.check:
        return 0
    chs, qs, cards, figs = build(frags)
    dump = lambda name, obj: (HERE / name).write_text(  # noqa: E731
        json.dumps(obj, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    dump("chapters.json", chs)
    dump("questions.json", qs)
    dump("cards.json", cards)
    dump("figures.json", figs)
    print("wrote chapters.json questions.json cards.json figures.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
